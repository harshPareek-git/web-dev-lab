// 1. DOM Collection
// There are 4 types of DOM Collection
// 1.1. HTMLCollection
// 1.2. NodeList
// 1.3. HTMLAllCollection
// 1.4. DOMTokenList

// 1.1. HTMLCollection
// HTMLCollection is a collection of all the elements in the HTML document.
// HTMLCollection is live.
// HTMLCollection is not an array.
// HTMLCollection is not a DOM object.
// HTMLCollection is not a DOM collection.

// 1.2. NodeList
// NodeList is a collection of all the nodes in the HTML document.
// NodeList is live.
// NodeList is not an array.
// NodeList is not a DOM object.
// NodeList is not a DOM collection.    

// 1.3. HTMLAllCollection
// HTMLAllCollection is a collection of all the elements in the HTML document.
// HTMLAllCollection is live.
// HTMLAllCollection is not an array.
// HTMLAllCollection is not a DOM object.
// HTMLAllCollection is not a DOM collection.   

// 1.4. DOMTokenList
// DOMTokenList is a collection of all the tokens in the HTML document.
// DOMTokenList is live.
// DOMTokenList is not an array.
// DOMTokenList is not a DOM object.
// DOMTokenList is not a DOM collection.

// 2. DOM Selector
// DOM Selector is a method to select the elements in the HTML document.
// DOM Selector is not an array.
// DOM Selector is not a DOM object.
// DOM Selector is not a DOM collection.

// 3. DOM Query Selector
// DOM Query Selector is a method to query the elements in the HTML document.
// DOM Query Selector is not an array.
// DOM Query Selector is not a DOM object.
// DOM Query Selector is not a DOM collection.  

// 4. DOM Traversal
// DOM Traversal is a method to traverse the elements in the HTML document.
// DOM Traversal is not an array.
// DOM Traversal is not a DOM object.
// DOM Traversal is not a DOM collection.   

// 5. DOM Manipulation
// DOM Manipulation is a method to manipulate the elements in the HTML document.
// DOM Manipulation is not an array.
// DOM Manipulation is not a DOM object.
// DOM Manipulation is not a DOM collection.    

// 6. DOM Events
// DOM Events is a method to handle the events in the HTML document.
// DOM Events is not an array.
// DOM Events is not a DOM object.
// DOM Events is not a DOM collection.          


